<?php
declare(strict_types=1);

namespace Dharma\Component\DharmaSitemap\Administrator\Service;

\defined('_JEXEC') or die;

/**
 * Собирает текст `llms.txt` (формат llmstxt.org: Markdown с названием, кратким описанием и списками ссылок по разделам)
 * из адресов, которые уже попали в карту сайта. Класс не обращается к Joomla и базе данных — только данные на входе.
 */
final class LlmsTxtBuilder
{
    /** Метка своего файла: по ней компонент отличает собственный llms.txt от чужого и не перезаписывает чужой. */
    public const MARKER = '<!-- Generated by Dharma Sitemap -->';

    private const DESCRIPTION_LENGTH = 220;

    /**
     * @param array{title:string,summary?:string,details?:string,rename?:array<string,string>,order?:list<string>,max_links?:int} $settings
     * @param list<array{url:string,title:?string,description:?string,section:?string}> $items записи в порядке карты
     */
    public static function build(array $settings, array $items): string
    {
        $rename = (array) ($settings['rename'] ?? []);
        $max = max(1, (int) ($settings['max_links'] ?? 300));
        $sections = [];
        $used = 0;

        foreach ($items as $item) {
            if ($used >= $max) {
                break;
            }

            $title = self::line((string) ($item['title'] ?? ''));

            if ($title === '') {
                // Без названия страница ничего не скажет модели: пропускаем, а не подставляем адрес.
                continue;
            }

            $section = self::line((string) ($item['section'] ?? ''));
            $section = $rename[$section] ?? $section;
            $section = $section !== '' ? $section : 'Страницы';
            $sections[$section][] = [$title, (string) $item['url'], self::description((string) ($item['description'] ?? ''))];
            $used++;
        }

        $sections = self::order($sections, (array) ($settings['order'] ?? []));
        $out = '# ' . self::line($settings['title']) . "\n";
        $summary = self::line((string) ($settings['summary'] ?? ''));

        if ($summary !== '') {
            $out .= "\n> " . $summary . "\n";
        }

        $details = trim(str_replace(["\r\n", "\r"], "\n", (string) ($settings['details'] ?? '')));

        if ($details !== '') {
            $out .= "\n" . $details . "\n";
        }

        foreach ($sections as $name => $links) {
            $out .= "\n## " . $name . "\n\n";

            foreach ($links as [$title, $url, $description]) {
                $out .= '- [' . self::escapeTitle($title) . '](' . self::escapeUrl($url) . ')' . ($description !== '' ? ': ' . $description : '') . "\n";
            }
        }

        return $out . "\n" . self::MARKER . "\n";
    }

    /** Разделы из настроек идут первыми в заданном порядке, остальные — в порядке появления. */
    private static function order(array $sections, array $order): array
    {
        $sorted = [];

        foreach ($order as $name) {
            $name = self::line((string) $name);

            if ($name !== '' && isset($sections[$name])) {
                $sorted[$name] = $sections[$name];
            }
        }

        return $sorted + $sections;
    }

    /** Одна строка без переносов и лишних пробелов. */
    private static function line(string $value): string
    {
        return trim((string) preg_replace('/\s+/u', ' ', $value));
    }

    private static function description(string $value): string
    {
        $text = self::line(html_entity_decode(strip_tags($value), ENT_QUOTES | ENT_HTML5, 'UTF-8'));

        if (mb_strlen($text) <= self::DESCRIPTION_LENGTH) {
            return $text;
        }

        $cut = mb_substr($text, 0, self::DESCRIPTION_LENGTH);
        $pos = mb_strrpos($cut, ' ');

        return rtrim($pos !== false && $pos > 100 ? mb_substr($cut, 0, $pos) : $cut, " ,;:-—") . '…';
    }

    private static function escapeTitle(string $title): string
    {
        return str_replace(['\\', '[', ']'], ['\\\\', '\\[', '\\]'], $title);
    }

    /** Скобки в адресе ломают Markdown-ссылку. */
    private static function escapeUrl(string $url): string
    {
        return str_replace([' ', '(', ')'], ['%20', '%28', '%29'], $url);
    }
}
